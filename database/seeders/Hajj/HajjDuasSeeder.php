<?php

namespace Database\Seeders\Hajj;

use App\Models\Article;
use App\Models\Category;
use App\Models\PostType;
use Illuminate\Database\Seeder;
use Illuminate\Support\Str;

/**
 * Seeds Duas & Zikir — with original Arabic, Bengali transliteration,
 * Bengali translation, and source reference.
 */
class HajjDuasSeeder extends Seeder
{
    public function run(): void
    {
        $duaType = PostType::where('slug', 'dua')->first();
        if (!$duaType) {
            $this->command->warn('⚠️  Dua PostType not found. Run HajjPostTypesSeeder first.');
            return;
        }

        // Category map
        $catMap = Category::whereIn('slug', [
            'dua-daily', 'dua-salah', 'dua-hajj',
            'dua-morning', 'dua-quran', 'dua-protection',
            'dua-forgiveness', 'dua-zikir',
        ])->pluck('id', 'slug');

        $duas = $this->getDuas();

        foreach ($duas as $dua) {
            $catId = $catMap[$dua['category']] ?? null;
            $slug  = $dua['slug'];

            Article::updateOrCreate(['slug' => $slug], [
                'title'               => $dua['title'],
                'excerpt'             => $dua['excerpt'],
                'body'                => $this->renderDuaBody($dua),
                'featured_image_path' => $this->categoryImage($dua['category']),
                'category_id'         => $catId,
                'post_type_id'        => $duaType->id,
                'is_breaking'         => false,
                'published_at'        => now(),
                'visibility'          => 'public',
            ]);
        }

        $this->command->info('✅ ' . count($duas) . ' Duas seeded.');
    }

    private function categoryImage(string $cat): string
    {
        return match (true) {
            str_contains($cat, 'hajj')       => 'https://images.unsplash.com/photo-1591604129939-f1efa4d9f7fa?w=1200&q=80',
            str_contains($cat, 'morning')    => 'https://images.unsplash.com/photo-1499159058454-75067059248a?w=1200&q=80',
            str_contains($cat, 'salah')      => 'https://images.unsplash.com/photo-1519817650390-64a93db51149?w=1200&q=80',
            str_contains($cat, 'forgive')    => 'https://images.unsplash.com/photo-1545987796-200677ee1011?w=1200&q=80',
            str_contains($cat, 'protect')    => 'https://images.unsplash.com/photo-1542816417-0983c9c9ad53?w=1200&q=80',
            str_contains($cat, 'zikir')      => 'https://images.unsplash.com/photo-1574943320219-553eb213f72d?w=1200&q=80',
            str_contains($cat, 'quran')      => 'https://images.unsplash.com/photo-1585036151513-9259aa9b5b37?w=1200&q=80',
            default                          => 'https://images.unsplash.com/photo-1564769662824-8e31e11e40c2?w=1200&q=80',
        };
    }

    private function renderDuaBody(array $dua): string
    {
        $source = htmlspecialchars($dua['source'] ?? '');
        $arabic = $dua['arabic'] ?? '';
        $translit = htmlspecialchars($dua['transliteration'] ?? '');
        $meaning  = htmlspecialchars($dua['meaning'] ?? '');
        $details  = $dua['details'] ?? '';
        $virtue   = isset($dua['virtue']) ? '<div class="mt-4 rounded-xl bg-[hsl(var(--accent)/0.1)] border border-[hsl(var(--accent)/0.3)] p-4"><p class="text-sm font-semibold">✨ ফজিলত</p><p class="text-sm mt-1">' . htmlspecialchars($dua['virtue']) . '</p></div>' : '';

        return <<<HTML
<div class="space-y-6">

  <!-- Arabic Text -->
  <div class="rounded-2xl bg-[hsl(var(--primary)/0.05)] border border-[hsl(var(--primary)/0.2)] p-6 text-center">
    <p class="text-3xl leading-loose font-arabic text-[hsl(var(--foreground))]" dir="rtl" lang="ar">{$arabic}</p>
  </div>

  <!-- Transliteration -->
  <div class="rounded-xl bg-[hsl(var(--muted))] p-4">
    <p class="text-xs font-semibold text-[hsl(var(--muted-foreground))] uppercase mb-1">উচ্চারণ</p>
    <p class="text-base italic text-[hsl(var(--foreground))]">{$translit}</p>
  </div>

  <!-- Meaning -->
  <div class="rounded-xl bg-[hsl(var(--card))] border border-[hsl(var(--border))] p-4">
    <p class="text-xs font-semibold text-[hsl(var(--muted-foreground))] uppercase mb-1">অর্থ</p>
    <p class="text-base text-[hsl(var(--foreground))]">{$meaning}</p>
  </div>

  <!-- Source -->
  <div class="flex items-center gap-2 text-xs text-[hsl(var(--muted-foreground))]">
    <span class="rounded-full bg-[hsl(var(--primary)/0.1)] px-3 py-1 text-[hsl(var(--primary))] font-medium">📚 সূত্র: {$source}</span>
  </div>

  {$virtue}

  {$details}

</div>
HTML;
    }

